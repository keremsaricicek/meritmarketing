#!/usr/bin/env node
'use strict';
/* Bundles the user manual into the application.
 *
 *   node scripts/build-help.js          # write src/renderer/scripts/help-content.js
 *                                       # and copy the screenshots
 *   node scripts/build-help.js --check  # exit 1 if the bundled copy is stale
 *
 * The manual is written once, in docs/ (USER-MANUAL.md and
 * KULLANIM-KILAVUZU.md), where it reads well on GitHub. The packaged
 * application leaves docs/ out, and the window's Content-Security-Policy
 * forbids fetching anything, so the Help screen reads a copy embedded in a
 * script: plain strings, rendered to DOM nodes by help.js. The screenshots
 * are copied next to the page, where `img-src 'self'` allows them.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DOCS = path.join(ROOT, 'docs');
const OUT_JS = path.join(ROOT, 'src', 'renderer', 'scripts', 'help-content.js');
const IMG_SRC = path.join(DOCS, 'manual-images');
const IMG_OUT = path.join(ROOT, 'src', 'renderer', 'manual-images');
const SOURCES = { en: 'USER-MANUAL.md', tr: 'KULLANIM-KILAVUZU.md' };

function bundle() {
  const content = {};
  for (const [lang, file] of Object.entries(SOURCES)) {
    content[lang] = fs.readFileSync(path.join(DOCS, file), 'utf8').replace(/\r\n/g, '\n');
  }
  return "'use strict';\n"
    + '/* GENERATED by scripts/build-help.js from docs/USER-MANUAL.md and\n'
    + '   docs/KULLANIM-KILAVUZU.md. Edit the Markdown, then run the script. */\n'
    + `window.HELP_CONTENT = Object.freeze(${JSON.stringify(content, null, 1)});\n`;
}

function images() {
  return fs.existsSync(IMG_SRC) ? fs.readdirSync(IMG_SRC).filter((f) => f.endsWith('.png')).sort() : [];
}

const check = process.argv.includes('--check');
const js = bundle();
if (check) {
  const problems = [];
  if (!fs.existsSync(OUT_JS) || fs.readFileSync(OUT_JS, 'utf8') !== js) problems.push('help-content.js is out of date');
  for (const name of images()) {
    const out = path.join(IMG_OUT, name);
    if (!fs.existsSync(out) || !fs.readFileSync(out).equals(fs.readFileSync(path.join(IMG_SRC, name)))) {
      problems.push(`manual-images/${name} is missing or different`);
    }
  }
  if (problems.length) {
    console.error(problems.join('\n') + '\nRun: node scripts/build-help.js');
    process.exit(1);
  }
  console.log('Bundled manual is up to date.');
} else {
  fs.writeFileSync(OUT_JS, js);
  fs.mkdirSync(IMG_OUT, { recursive: true });
  for (const name of fs.readdirSync(IMG_OUT)) if (!images().includes(name)) fs.unlinkSync(path.join(IMG_OUT, name));
  for (const name of images()) fs.copyFileSync(path.join(IMG_SRC, name), path.join(IMG_OUT, name));
  console.log(`Wrote ${path.relative(ROOT, OUT_JS)} and ${images().length} image(s).`);
}

module.exports = { bundle, images, SOURCES };
