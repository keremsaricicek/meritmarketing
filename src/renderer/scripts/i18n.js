let i18nLang = 'en';

function currentLanguage(){ return i18nLang; }

function i18nFill(text, vars){
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) && vars[name] !== undefined && vars[name] !== null ? String(vars[name]) : m);
}

/** The text for `key` in the active language, with {name} placeholders filled. */
function t(key, vars){
  if (key === undefined || key === null) return '';
  const k = String(key);
  let text;
  if (i18nLang === 'tr' && Object.prototype.hasOwnProperty.call(I18N_TR, k)) text = I18N_TR[k];
  else if (Object.prototype.hasOwnProperty.call(I18N_EN, k)) text = I18N_EN[k];
  else text = k;
  return i18nFill(text, vars);
}
/** Singular/plural pair; `{n}` is filled with the count. */
function tn(n, one, other, vars){
  return t(Number(n) === 1 ? one : other, { n, ...(vars || {}) });
}
/** t() escaped for a markup template. */
function te(key, vars){ return escapeHtml(t(key, vars)); }

/** A sentence written by the main process, in the active language when it is
    one we know, otherwise unchanged. */
function tNotice(text){
  if (text === undefined || text === null) return '';
  const s = String(text);
  if (i18nLang !== 'tr' || !s) return s;
  if (Object.prototype.hasOwnProperty.call(I18N_TR, s)) return I18N_TR[s];
  for (const [re, out] of I18N_TR_PATTERNS){
    const m = re.exec(s);
    /* A captured status or role code (UPCOMING, MARKETING…) is shown in
       Turkish too; names and dates pass through untouched. */
    if (m) return out.replace(/\{(\d)\}/g, (_, i) => {
      const v = m[Number(i)] ?? '';
      return /^[A-Z][A-Z_]+$/.test(v) && Object.prototype.hasOwnProperty.call(I18N_TR, v) ? I18N_TR[v] : v;
    });
  }
  /* "admin: Created guest …" — a notification names the actor first. */
  const prefixed = /^([^\s:]{1,40}): (.+)$/s.exec(s);
  if (prefixed){
    const rest = tNotice(prefixed[2]);
    if (rest !== prefixed[2]) return `${prefixed[1]}: ${rest}`;
  }
  return s;
}
/** The message of an error envelope from the main process. Codes are never
    rewritten; only the human sentence is translated. */
function tErr(error){
  if (!error) return '';
  return tNotice(error.message || '');
}

const I18N_ROLE_LABELS = { ADMIN:'Administrator', MANAGER:'Manager', MARKETING:'Marketing' };
function roleLabel(role){ return I18N_ROLE_LABELS[role] ? t(I18N_ROLE_LABELS[role]) : ''; }

/** Upper case by the rules of the active language (i → İ in Turkish). */
function upperLocale(text){
  return String(text ?? '').toLocaleUpperCase(i18nLang === 'tr' ? 'tr-TR' : 'en-US');
}

/** Fill every data-i18n* attribute under `root` from the active dictionary. */
function applyI18n(root){
  const scope = root && root.querySelectorAll ? root : document;
  for (const node of scope.querySelectorAll('[data-i18n]')) node.textContent = t(node.getAttribute('data-i18n'));
  for (const attr of ['placeholder', 'title', 'aria-label']){
    for (const node of scope.querySelectorAll(`[data-i18n-${attr}]`)) node.setAttribute(attr, t(node.getAttribute(`data-i18n-${attr}`)));
  }
}

function storedLanguage(){
  try {
    const v = window.localStorage.getItem(I18N_STORAGE_KEY);
    return I18N_LANGUAGES.includes(v) ? v : null;
  } catch (_) { return null; }
}
function rememberLanguage(lang){
  try { window.localStorage.setItem(I18N_STORAGE_KEY, lang); } catch (_) { /* storage unavailable: nothing to remember */ }
}

/* The language switch on the login and setup cards shows which one is on. */
function paintLanguageSwitches(){
  document.querySelectorAll('[data-lang-choice]').forEach(b => {
    const on = b.getAttribute('data-lang-choice') === i18nLang;
    b.classList.toggle('active', on);
    b.setAttribute('aria-pressed', String(on));
  });
  const sel = document.getElementById('setLanguage');
  if (sel) sel.value = i18nLang;
}

/**
 * Switch the interface language. No reload: static text is refilled at once
 * and the screens that are open draw themselves again in the new language.
 * `persist` saves it as the signed-in user's personal preference.
 */
function applyLanguage(lang, persist){
  const next = I18N_LANGUAGES.includes(lang) ? lang : 'en';
  const changed = next !== i18nLang;
  i18nLang = next;
  document.documentElement.lang = next;
  rememberLanguage(next);
  applyI18n(document);
  paintLanguageSwitches();
  if (persist && typeof saveSetting === 'function') Promise.resolve(saveSetting('appearance.language', next)).catch(() => {});
  if (changed && typeof refreshAfterLanguageChange === 'function') refreshAfterLanguageChange();
}
/* Settings › Appearance › Language. */
function setLanguageFromSelect(value){ applyLanguage(value, true); }
/* Login / setup cards: nobody is signed in, so only this computer remembers. */
function setLoginLanguage(lang){ applyLanguage(lang, false); }

function initI18n(){
  i18nLang = storedLanguage() || 'en';
  document.documentElement.lang = i18nLang;
  applyI18n(document);
  paintLanguageSwitches();
}
