/* =====================================================================
   Interface language: English (default) and Turkish.

   Two kinds of key live here:

   - `h.*` keys name the static text of index.html. An element carries
     data-i18n="h.save" (its text), data-i18n-placeholder, data-i18n-title
     or data-i18n-aria-label, and applyI18n() fills them from the active
     dictionary. Every such key exists in BOTH I18N_EN and I18N_TR — a test
     holds that.

   - Text built in script is written in English and passed through t():
     t('Note added'), t('{n} rows → {file}', { n, file }). The English
     sentence is its own key, so the English interface needs no table at
     all; I18N_TR translates it. A phrase with no Turkish entry falls back
     to the English text rather than to a key name — a test lists every
     literal passed to t()/te()/tn() and requires a Turkish entry.

   Translated strings are DATA. They reach the page through textContent,
   or through te() — which escapes — when a template builds markup. Values
   interpolated with {name} are escaped together with the sentence.

   Messages written by the main process (validation errors, notification
   texts, audit descriptions) keep their English source and codes; tNotice()
   shows a Turkish rendering of the common ones and passes anything it does
   not recognise through unchanged.
   ===================================================================== */

